  await stage(p, 'out'); await sh(p, 'stage-check-out');
  await bar(p, 'pi'); await p.tap('[data-act=pview][data-v=p]'); await sh(p, 'san-pham-theo-mau-newest-first');
  await p.evaluate(() => { document.querySelector('#pi').scrollTop = 1250; }); await sh(p, 'theo-mau-collections-scrolled');
  await p.evaluate(() => { document.querySelector('#pi').scrollTop = 0; }); await p.tap('#pfilt [data-v=skirt]'); await sh(p, 'theo-mau-filter-vay');
  await p.tap('#pfilt [data-v=all]'); await p.tap('[data-act=pview][data-v=s]'); await sh(p, 'theo-set-two-photos');
  await p.tap('[data-act=setsugg][data-a="soft-halter-top-white"]'); await sh(p, 'set-sheet-pair-illustration');
  await p.fill('[data-sprice]', '800000'); await sh(p, 'set-custom-price'); await close(p);
  await p.tap('[data-act=pview][data-v=p]'); await p.tap('[data-open="p:lace-top"]'); await sh(p, 'product-sheet-photo-header');
  await p.fill('.acard [data-eta=info]', (await p.$eval('.acard [data-eta=info]', e => e.value)) + '\n' + Array.from({ length: 20 }, (_, i) => 'Dòng thêm ' + (i + 1)).join('\n')); await sh(p, 'product-long-text-scrolls-inside');
  await p.tap('[data-act=ebreset]'); await p.tap('[data-act=addline][data-v=M]'); await close(p); await sh(p, 'round-order-button-badge');
  await p.tap('#nav [data-act=settings]'); await sh(p, 'settings-gear');
  await p.close();
  p = await mk({ fakeVV: true }); await stage(p, 'order'); await p.tap('#ores [data-act=oadd] >> nth=0'); await p.focus('[data-eta=order]'); await p.evaluate(() => window.__setKb(336)); await sh(p, 'keyboard-emulated-order');
