  const close = async p => { await p.tap('.sheet >> nth=-1 >> [data-act=shclose]'); await p.waitForTimeout(450); };
  let p = await mk(); await sh(p, 'home');
  await stage(p, 'greet'); await sh(p, 'quick-reply-chao-hoi');
  await p.tap('[data-open="f:open-first"]'); await sh(p, 'greeting-editable-box');
  await p.tap('#mcopy'); await p.waitForTimeout(250); await sh(p, 'greeting-copied');
  await p.waitForTimeout(900); await p.tap('[data-act=pchoose]'); await sh(p, 'product-picker-photos-filters');
  await close(p);
  await stage(p, 'size'); await sh(p, 'stage-tu-van-size');
  await stage(p, 'info'); await sh(p, 'stage-xin-thong-tin');
  await stage(p, 'order'); await sh(p, 'stage-tao-don-empty');
