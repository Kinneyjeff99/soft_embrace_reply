  await p.tap('[data-open="p:noir-midi-skirt"]'); await p.fill('.acard [data-eta=info]', 'Bản sửa tay\n' + await p.$eval('.acard [data-eta=info]', e => e.value)); await sh(p, 'dark-product-edited');
